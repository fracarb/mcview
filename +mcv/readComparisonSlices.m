function [primary, secondary] = readComparisonSlices( ...
        source, datasetInfo, primaryInfo, secondaryInfo, ...
        primaryX, primaryY, primaryIndices)
%READCOMPARISONSLICES Legge due campi usando lo stesso snapshot temporale.

    [primaryData, primaryXCoordinate, primaryYCoordinate, ...
        primarySelection, primaryAxes] = mcv.readVariableSlice( ...
        source, datasetInfo, primaryInfo, primaryX, primaryY, primaryIndices);

    [secondaryX, secondaryY, secondaryIndices] = ...
        mcv.matchSliceDimensions(primaryInfo, secondaryInfo, ...
        primaryX, primaryY, primarySelection.start, datasetInfo);
    secondaryIndices = inheritTemporalSelection(source, datasetInfo, ...
        primaryInfo, secondaryInfo, primarySelection.start, secondaryIndices);
    [secondaryData, secondaryXCoordinate, secondaryYCoordinate, ...
        secondarySelection, secondaryAxes] = mcv.readVariableSlice( ...
        source, datasetInfo, secondaryInfo, secondaryX, secondaryY, ...
        secondaryIndices);

    primary = sliceResult(primaryData, primaryXCoordinate, ...
        primaryYCoordinate, primaryAxes, primarySelection, ...
        primaryX, primaryY);
    secondary = sliceResult(secondaryData, secondaryXCoordinate, ...
        secondaryYCoordinate, secondaryAxes, secondarySelection, ...
        secondaryX, secondaryY);
end

function secondaryIndices = inheritTemporalSelection( ...
        source, datasetInfo, primaryInfo, secondaryInfo, ...
        primaryIndices, secondaryIndices)
    primaryTime = mcv.findTemporalDimension(datasetInfo, primaryInfo);
    secondaryTime = mcv.findTemporalDimension(datasetInfo, secondaryInfo);
    if primaryTime == 0 || secondaryTime == 0 || ...
            primaryTime > numel(primaryIndices)
        return;
    end

    primaryIndex = primaryIndices(primaryTime);
    secondaryIndex = min(primaryIndex, secondaryInfo.Size(secondaryTime));
    try
        primaryAxis = mcv.readAxis(source, datasetInfo, ...
            primaryInfo.Dimensions(primaryTime), ...
            primaryInfo.Size(primaryTime), primaryInfo);
        secondaryAxis = mcv.readAxis(source, datasetInfo, ...
            secondaryInfo.Dimensions(secondaryTime), ...
            secondaryInfo.Size(secondaryTime), secondaryInfo);
        if primaryAxis.isTime && secondaryAxis.isTime && ...
                primaryIndex <= numel(primaryAxis.plotValues)
            requestedTime = double(primaryAxis.plotValues(primaryIndex));
            candidates = double(secondaryAxis.plotValues(:));
            finiteCandidates = find(isfinite(candidates));
            if isfinite(requestedTime) && ~isempty(finiteCandidates)
                [~, nearest] = min(abs( ...
                    candidates(finiteCandidates) - requestedTime));
                secondaryIndex = finiteCandidates(nearest);
            end
        end
    catch
        % Se le coordinate non sono leggibili, conserva lo stesso indice.
    end
    secondaryIndices(secondaryTime) = secondaryIndex;
end

function result = sliceResult(data, xCoordinate, yCoordinate, ...
        axesInfo, selection, xDimension, yDimension)
    result = struct( ...
        'data', data, ...
        'x', xCoordinate, ...
        'y', yCoordinate, ...
        'axesInfo', axesInfo, ...
        'selection', selection, ...
        'xDimension', xDimension, ...
        'yDimension', yDimension);
end
